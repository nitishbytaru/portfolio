"use server";

import { redirect } from "next/navigation";
import { CONTENT_FILES, describeIssues, SCHEMAS, type ContentFile } from "@/lib/schema";
import { assertAdmin, endSession, NotSignedInError } from "@/lib/server/session";
import { commitFiles, ConflictError, GitHubError, type CommitEntry } from "@/lib/server/github";
import { contentPath } from "@/lib/server/admin-content";
import { ConfigError } from "@/lib/server/env";
import { UPLOAD_PATH } from "@/lib/server/uploads";

export interface Upload {
  /** Repo path, e.g. public/uploads/2026/1a2b3c4d5e6f7a8b.webp */
  path: string;
  /** Blob sha returned by the upload route. */
  sha: string;
}

export type SaveResult =
  | { ok: true; sha: string; commitUrl: string }
  | { ok: false; error: string; issues?: string[]; conflict?: boolean; signedOut?: boolean };

/**
 * Saves one content file, plus any images it now references, as a single commit.
 * `baseSha` is the version the editor loaded; a newer version on GitHub is never overwritten.
 */
export async function saveContent(input: { file: ContentFile; data: unknown; baseSha: string; uploads?: Upload[] }): Promise<SaveResult> {
  try {
    await assertAdmin();

    if (!CONTENT_FILES.includes(input.file)) return { ok: false, error: "Unknown content file." };
    if (typeof input.baseSha !== "string" || !/^[a-f0-9]{40}$/.test(input.baseSha)) return { ok: false, error: "Missing version. Reload and try again." };

    const parsed = SCHEMAS[input.file].safeParse(input.data);
    if (!parsed.success) return { ok: false, error: "Some fields need fixing.", issues: describeIssues(parsed.error) };

    const text = JSON.stringify(parsed.data, null, 2) + "\n";
    const entries: CommitEntry[] = [{ path: contentPath(input.file), content: text }];

    // Only uploads this save actually uses are committed. Paths were generated by the server.
    const uploads = Array.isArray(input.uploads) ? input.uploads : [];
    for (const upload of uploads) {
      if (typeof upload?.path !== "string" || typeof upload?.sha !== "string") return { ok: false, error: "Invalid upload." };
      if (!UPLOAD_PATH.test(upload.path) || !/^[a-f0-9]{40}$/.test(upload.sha)) return { ok: false, error: "Invalid upload." };
      const publicPath = upload.path.replace(/^public/, "");
      if (text.includes(JSON.stringify(publicPath)) && !entries.some((entry) => entry.path === upload.path)) {
        entries.push({ path: upload.path, sha: upload.sha });
      }
    }

    const result = await commitFiles(entries, `content: update ${input.file}`, { [contentPath(input.file)]: input.baseSha });
    return { ok: true, sha: result.shas[contentPath(input.file)], commitUrl: result.url };
  } catch (error) {
    if (error instanceof NotSignedInError) return { ok: false, error: error.message, signedOut: true };
    if (error instanceof ConflictError) return { ok: false, error: error.message, conflict: true };
    if (error instanceof GitHubError || error instanceof ConfigError) return { ok: false, error: error.message };
    console.error("saveContent failed", error);
    return { ok: false, error: "Something went wrong and nothing was saved. Try again." };
  }
}

export async function signOut() {
  await endSession();
  redirect("/admin/login");
}
